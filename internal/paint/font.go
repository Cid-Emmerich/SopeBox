// TextWidth returns the width in units of s drawn at the given size.
func TextWidth(s string, size float64) float64 {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	cell := size / 5
	return float64(n)*4*cell - cell
}

// Text draws s with its top-left corner at x,y; size is the glyph height.
// Unknown characters draw as a small box. Letters are upper-cased.
func (p *Painter) Text(x, y, size float64, s string, c RGB) {
	cell := size / 5
	for _, r := range strings.ToUpper(s) {
		rows, ok := font3x5[r]
		if !ok {
			rows = [5]string{"###", "#.#", "#.#", "#.#", "###"}
		}
		for ry, row := range rows {
			for rx, ch := range row {
				if ch == '#' {
					p.Rect(x+float64(rx)*cell, y+float64(ry)*cell, cell*1.02, cell*1.02, c)
				}
			}
		}
		x += 4 * cell
	}
}

// TextCentred draws s centred on cx.
func (p *Painter) TextCentred(cx, y, size float64, s string, c RGB) {
	p.Text(cx-TextWidth(s, size)/2, y, size, s, c)
}
